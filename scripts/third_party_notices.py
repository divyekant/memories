#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from server/Cargo.lock and mcp-server/package-lock.json.

Usage: python3 scripts/third_party_notices.py [--check]
--check: exit 1 if the file is not current or a license is not on the allow list.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"

# Licenses that let us ship the code under MIT. An expression passes if each
# AND part has at least one allowed choice.
ALLOWED = {
    "MIT", "MIT-0", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause",
    "BSD-3-Clause", "ISC", "Zlib", "Unlicense", "0BSD", "CC0-1.0", "Unicode-3.0",
    "BSL-1.0", "CDLA-Permissive-2.0", "Python-2.0",
}

HEADER = """# Third-party notices

Memories is licensed under the MIT License (see `LICENSE`). It uses the
third-party packages below. Each package keeps its own license and copyright.
Keep this attribution when you distribute a build.

Do not edit this file by hand. Run `python3 scripts/third_party_notices.py`
after a dependency change. CI runs it with `--check`.

## Components in the Docker image (`ghcr.io/divyekant/memories`)

| Component | Version | License | Source |
|---|---|---|---|
| Debian base image (`debian:trixie-slim`) and `ca-certificates` | trixie | Several free licenses, see `/usr/share/doc/*/copyright` in the image | https://www.debian.org |
| Embedding model `sentence-transformers/all-MiniLM-L6-v2` (downloaded at the first start, not in the image) | Hub revision of the first start | Apache-2.0 | https://huggingface.co/sentence-transformers/all-MiniLM-L6-v2 |
| Qdrant (separate container, not in the image) | 1.15.4 | Apache-2.0 | https://github.com/qdrant/qdrant |

## Python server v5 (rollback reference)

The Python server stays in the repository for the rollback. To list the
licenses of its locked packages, run:

```bash
uv sync
uv pip install pip-licenses
uv run pip-licenses --from=mixed --format=markdown
```
"""


def allowed(expr: str) -> bool:
    expr = expr.replace("/", " OR ").replace("(", " ").replace(")", " ")
    for part in re.split(r"\s+AND\s+", expr.strip()):
        choices = [c.strip() for c in re.split(r"\s+OR\s+", part) if c.strip()]
        if not any(c in ALLOWED for c in choices):
            return False
    return True


def rust_rows():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT / "server", check=True, capture_output=True, text=True).stdout)
    members = set(meta["workspace_members"])
    return sorted(
        (p["name"], p["version"], p.get("license") or "", p.get("repository") or "")
        for p in meta["packages"] if p["id"] not in members)


def npm_rows():
    lock = json.loads((ROOT / "mcp-server" / "package-lock.json").read_text())
    rows = []
    for path, p in lock["packages"].items():
        if not path or p.get("dev"):
            continue
        name = path.rsplit("node_modules/", 1)[-1]
        rows.append((name, p.get("version", ""), p.get("license") or "", ""))
    return sorted(set(rows))


def table(rows):
    lines = ["| Package | Version | License | Repository |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {lic or 'unknown'} | {r} |" for n, v, lic, r in rows]
    return "\n".join(lines)


def main() -> int:
    rust, npm = rust_rows(), npm_rows()
    bad = [r for r in rust + npm if not allowed(r[2])]
    text = (HEADER
            + "\n## Rust crates of the server (`server/Cargo.lock`, all target platforms)\n\n"
            + table(rust)
            + "\n\n## npm packages of the MCP server and CLI (`mcp-server/package-lock.json`, no dev packages)\n\n"
            + table(npm) + "\n")
    for n, v, lic, _ in bad:
        print(f"license not on the allow list: {n} {v} {lic!r}", file=sys.stderr)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print("THIRD_PARTY_NOTICES.md is not current: run scripts/third_party_notices.py", file=sys.stderr)
            return 1
        return 1 if bad else 0
    OUT.write_text(text)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
